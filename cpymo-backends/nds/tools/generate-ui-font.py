"""Generate ROM UI subsets from the repository's OFL bitmap font sources."""
from pathlib import Path
import sys,re,json,hashlib
backend=Path(__file__).resolve().parents[1]
repo=backend.parents[1]
converter=repo/'cpymo-tool/nds-converter'
sys.path.insert(0,str(converter))
from pixel_font import read_bdf,read_hex
header=backend/'source/ui-fallback-font.h'
codes=set(range(32,127))
codes.update(map(int,re.search(r'ui_fallback_codes\[\]=\{([^}]+)',header.read_text(encoding='utf8')).group(1).split(',')))
files=[backend/'source'/n for n in ('launcher.h','theme-nds.h','ui-language-nds.c','ui-language-extra.h','cpymo_config_ui.c')]
texts=[p.read_text(encoding='utf8') for p in files]
core=(repo/'cpymo/cpymo_localization.c').read_text(encoding='utf8')
texts.append(core[:core.index('STR_I(enu,')])
for text in texts:
    for match in re.finditer(r'"((?:\\.|[^"\\])*)"',text):
        try:literal=json.loads('"'+match.group(1)+'"')
        except ValueError:continue
        codes.update(ord(c) for c in literal if ord(c)>=32)
codes=sorted(codes)
small_source=converter/'fonts/pixel/Fusion/fusion-pixel-12px-proportional-zh_hans.bdf.gz'
large_source=converter/'fonts/pixel/Unifont/unifont-17.0.05.hex.gz'
small=read_bdf(small_source,set(codes));large=read_hex(large_source,set(codes))
assert set(codes)<=small.keys() and set(codes)<=large.keys()
lines=['/* Generated by tools/generate-ui-font.py. Do not hand-edit.\n'
       '   Fusion Pixel 12px / GNU Unifont 16px subsets, OFL-1.1.\n'
       '   See licenses/Fusion-OFL.txt and licenses/Unifont/. */',
       'static const unsigned ui_fallback_codes[]={'+','.join(map(str,codes))+'};']
for prefix,glyphs in (('ui_fallback',small),('ui_large',large)):
    lines.append('static const unsigned char '+prefix+'_advances[]={'+','.join(str(glyphs[c][0]) for c in codes)+'};')
    lines.append('static const unsigned short '+prefix+'_rows[][16]={\n'+',\n'.join('{'+','.join(map(str,glyphs[c][1]))+'}' for c in codes)+'};')
lines.append('static int ui_fallback_glyph(unsigned cp){int lo=0,hi=sizeof ui_fallback_codes/sizeof *ui_fallback_codes-1;while(lo<=hi){int m=(lo+hi)/2;if(ui_fallback_codes[m]==cp)return m;if(ui_fallback_codes[m]<cp)lo=m+1;else hi=m-1;}return -1;}')
header.write_text('\n'.join(lines)+'\n',encoding='utf8')
print(json.dumps({'glyphs':len(codes),'ROM_table_bytes':len(codes)*70,'small_source_sha256':hashlib.sha256(small_source.read_bytes()).hexdigest(),'large_source_sha256':hashlib.sha256(large_source.read_bytes()).hexdigest()},indent=2))
