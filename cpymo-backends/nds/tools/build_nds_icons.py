#!/usr/bin/env python3
"""Derive NDS-only icon sizes from the pinned full-square artwork.

No crop or new corner mask; keep desktop sources and outputs independent.
The 32px banner reserves transparent palette index zero even though all
actual pixels are opaque. Runtime sizes use native RGB555, not that palette.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageFilter

NDS = Path(__file__).resolve().parents[1]
SOURCE_SHA256 = 'f3bb25e8d37c8c8201969c8a59d629983544786c80903c5c27de848ffe532312'
SOURCE_RGBA_SHA256 = '7e157efd3272febbd8431f70e9e9fdd80fa13fecd3ef83d0299ba489210b5c10'
BORDER_RGB555 = (14, 12, 10)
BORDER_RGB = tuple(v * 255 // 31 for v in BORDER_RGB555)

def sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()

def rgb555(image: Image.Image) -> Image.Image:
    image = image.convert('RGB')
    image.putdata([tuple((v >> 3) * 255 // 31 for v in rgb)
                   for rgb in image.get_flattened_data()])
    return image

def pixels(image: Image.Image) -> list[int]:
    return [0x8000 | sum(round(v * 31 / 255) << shift
                         for v, shift in zip(rgb, (0, 5, 10)))
            for rgb in image.get_flattened_data()]

def derive(source: Path) -> dict[str, Image.Image]:
    if sha(source.read_bytes()) != SOURCE_SHA256:
        raise ValueError('Wrong NDS full-square source file')
    with Image.open(source) as opened:
        if opened.size != (1254, 1254) or sha(opened.convert('RGBA').tobytes()) != SOURCE_RGBA_SHA256:
            raise ValueError('Wrong NDS source pixels or dimensions')
        master = opened.convert('RGB')
    result = {}
    for size, name in ((32, 'icon.png'), (24, 'icon-small.png'), (64, 'icon-splash.png')):
        content = master.resize((size - 2, size - 2), Image.Resampling.LANCZOS)
        if size <= 32:
            content = content.filter(ImageFilter.UnsharpMask(radius=.55, percent=80, threshold=2))
        if size == 32:
            content = content.quantize(colors=14, method=Image.Quantize.MEDIANCUT,
                                       kmeans=8, dither=Image.Dither.NONE).convert('RGB')
        content = rgb555(content)
        canvas = Image.new('RGB', (size, size), BORDER_RGB)
        canvas.paste(content, (1, 1))
        result[name] = canvas
    return result

def build(source: Path, output: Path) -> dict:
    images = derive(source)
    assets, code = output / 'assets', output / 'source'
    assets.mkdir(parents=True, exist_ok=True)
    code.mkdir(parents=True, exist_ok=True)
    for name, image in images.items():
        image.save(assets / name)
    banner = images['icon.png']
    colors = sorted(set(banner.get_flattened_data()))
    if len(colors) > 15:
        raise ValueError('NDS banner exceeds 15 opaque colors')
    lookup = {c: i + 1 for i, c in enumerate(colors)}
    bmp = Image.new('P', banner.size)
    palette = [0, 0, 0] + [v for color in colors for v in color]
    bmp.putpalette(palette + [0] * (768 - len(palette)))
    bmp.putdata([lookup[c] for c in banner.get_flattened_data()])
    bmp.save(assets / 'icon.bmp')
    lines = ['/* Generated by tools/build_nds_icons.py. NDS-only warm-grey-brown frames.',
             ' * Complete artwork, no crop; all displayed pixels are opaque RGB555. */']
    for name, symbol in (('icon.png', 'app_icon'), ('icon-small.png', 'app_icon_small'),
                         ('icon-splash.png', 'app_icon_splash')):
        data = pixels(images[name])
        lines.append(f'static const u16 {symbol}[{len(data)}]={{')
        lines.extend(' ' + ','.join(map(str, data[i:i+32])) + ',' for i in range(0, len(data), 32))
        lines.append('};')
    (code / 'app-icon.h').write_text('\n'.join(lines) + '\n', encoding='ascii')
    paths = [assets / name for name in images] + [assets / 'icon.bmp', code / 'app-icon.h']
    manifest = {
        'source': 'icon-source-square.png', 'source_sha256': SOURCE_SHA256,
        'source_rgba_sha256': SOURCE_RGBA_SHA256, 'source_size': [1254, 1254],
        'border_rgb555': list(BORDER_RGB555), 'border_rgb': list(BORDER_RGB),
        'border_pixels': 1, 'uniform_scale': True, 'crop_or_corner_mask': False,
        'resampling': 'LANCZOS',
        'small_detail_filter': {'sizes': [24, 32], 'radius': .55, 'percent': 80, 'threshold': 2},
        'banner_quantization': {'art_colors': 14, 'border_color': 1,
                                'method': 'MEDIANCUT', 'kmeans': 8, 'dither': 'NONE',
                                'transparent_palette_index': 0, 'actual_opaque_colors': len(colors)},
        'runtime_sizes': [24, 32, 64],
        'outputs': {str(path.relative_to(output)): {'bytes': path.stat().st_size,
                    'sha256': sha(path.read_bytes())} for path in paths},
    }
    for name, image in images.items():
        manifest['outputs']['assets/' + name].update(
            size=list(image.size), rgb_sha256=sha(image.tobytes()))
    (assets / 'NDS-ICON-MANIFEST.json').write_text(json.dumps(manifest, indent=2) + '\n', encoding='ascii')
    return manifest

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=NDS / 'assets/icon-source-square.png')
    parser.add_argument('--output', type=Path, default=NDS)
    args = parser.parse_args()
    print(json.dumps(build(args.source, args.output), indent=2))
